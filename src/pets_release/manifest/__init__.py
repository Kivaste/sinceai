"""Privacy manifest: closed schema, canonical JSON and validation (ticket 02).

Public API (import from ``pets_release.manifest``):

Canonical JSON
    canonical_bytes(obj) -> bytes      sorted keys, separators ``,``/``:``, UTF-8, no NaN; raises on non-str keys
    canonical_digest(obj) -> str       sha256 hex of canonical_bytes(obj)
    loads_strict(raw) -> obj           JSON parse that rejects duplicate keys and NaN/Infinity (ValueError)

Signature payload
    signing_bytes(manifest) -> bytes   canonical bytes of the manifest with the ``signature`` key removed
    compute_signature(manifest, signing_key: bytes) -> str
                                       HMAC-SHA256 hex over signing_bytes. Key derivation (HKDF of the master key,
                                       info="manifest-signature") belongs to the caller.

Schema and validation
    SCHEMA_VERSION                     the only accepted ``schemaVersion`` value
    MANIFEST_SCHEMA                    JSON Schema (2020-12) dict; closed (``additionalProperties: false``) at every
                                       record level. Maps keyed by names (``bindings.files`` etc.) constrain their
                                       key pattern and value schema instead.
    LABEL_ASSERTIONS, ALL_ASSERTIONS   export-assertion names
    SCENARIOS                          scenarios a manifest may be issued for ("HEALTH-S1", "CS-S1")
    required_assertions(scenario)      exact, sorted tuple of assertion names the scenario's manifest must carry
    validate_manifest(obj) -> list[str]
                                       sorted, content-free error codes ``"<json path>: <rule>"``; empty = valid.
                                       Runs the schema plus cross-field rules (evidence <-> assertions <-> gate
                                       checks <-> bindings.checkVersions, bindings.files == contract.files, list
                                       order and uniqueness). Never echoes instance values.
    validate_manifest_file(path) -> list[str]
                                       reads bytes, strict-parses, requires the bytes to be canonical, validates.
                                       Accepts a release folder (reads ``privacy_manifest.json``).
    not_measured(reason) -> dict       the schema-valid "not yet measured" value for any ``measured.*`` section
                                       and any residual-risk ``rate``.

CLI
    python -m pets_release.manifest validate <manifest.json | release_dir>
        exit 0 VALID, 1 INVALID (prints error codes, no values), 2 usage error / unreadable path.

Fixture: ``tests/fixtures/manifest/release/`` is a hand-made HEALTH-S1 release (synthetic rows) whose
``privacy_manifest.json`` validates; it is regenerated by ``tests/fixtures/manifest/build_fixture.py``.
"""

