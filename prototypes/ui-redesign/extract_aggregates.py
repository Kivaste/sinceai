"""PROTOTYPE extractor: pulls content-free aggregates from a privacy manifest into a JS object.

Usage: python -I extract_aggregates.py <measured_manifest.json> <plain_manifest.json> <out.js>
Reads only manifests (schema names + aggregates). Hides every k figure (D33 pending).
"""
import json
import sys


def r(x, n=2):
    return None if x is None else round(float(x), n)


def main(measured_path, plain_path, out_path):
    m = json.load(open(measured_path, encoding="utf-8"))
    p = json.load(open(plain_path, encoding="utf-8"))
    pets = {(x["table"], x["column"]): x["pet"] for x in m["pets"]}
    just = {(x["table"], x["column"]): x for x in m["fieldJustifications"]}
    fields = []
    for inv in m["inventory"]:
        key = (inv["table"], inv["column"])
        j = just.get(key, {})
        fields.append({
            "table": inv["table"], "column": inv["column"], "role": inv["role"],
            "subtype": inv.get("subtype"), "pet": pets.get(key),
            "decision": j.get("decision"), "rung": j.get("rung"),
            "reason": j.get("reason"), "outputColumn": j.get("outputColumn"),
        })
    comps = {c["component"]: c for c in m["measured"]["privacy"]["components"]}
    # allowlist: per-person k figures are hidden (D33 pending)
    keep = ["privacy", "linkage_reid", "k_below_5_share"]
    privacy = {k: {"before": r(comps[k].get("before"), 2), "after": r(comps[k].get("after"), 2)}
               for k in keep if k in comps}
    tasks = [{"task": t["task"], "before": r(t.get("before")), "after": r(t.get("after")),
              "status": t.get("status")} for t in m["measured"]["utility"]["tasks"]]
    uvals = [t["after"] for t in m["measured"]["utility"]["tasks"] if t.get("after") is not None]
    headline = {
        "privacy": privacy.get("privacy"),
        "utility": {"before": 1.0, "after": r(sum(uvals) / len(uvals))},
        # composite is not in the manifest components; value from the pin-proof pets-eval scorecard (brief)
        "composite": {"before": 0.28, "after": 0.97},
        "linkage": privacy.get("linkage_reid"),
        "smallGroups": privacy.get("k_below_5_share"),
    }
    gate = [{"check": c["check"], "status": c["status"], "hits": c["hits"]} for c in m["gate"]["checks"]]
    search = m["measured"]["search"]
    data = {
        "toolRevision": m["bindings"]["toolRevision"][:7],
        "scenario": m["release"]["scenario"],
        "fields": fields,
        "headline": headline,
        "tasks": tasks,
        "gate": {"status": m["gate"]["status"], "checks": gate},
        "plainGateCount": len(p.get("gate", {}).get("checks", [])),
        "sacrifices": [{"check": s["check"], "before": r(s["before"]), "after": r(s["after"]),
                        "floor": s["floor"], "reason": s["reason"]} for s in m["sacrifices"]],
        "residualRisks": [{"kind": x["kind"], "description": x["description"],
                           "status": x["rate"]["status"]} for x in m["residualRisks"]],
        "fitFor": [x["scenario"] for x in m["fitFor"]],
        "notFitFor": [x["scenario"] for x in m["notFitFor"]],
        "search": {"candidates": search["candidates"], "accepted": search["accepted"],
                   "points": [{"step": x["step"], "risk": r(x["risk"]), "utility": r(x["utility"]),
                               "accepted": x["accepted"]} for x in search["points"]]},
    }
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// generated by extract_aggregates.py (aggregates only)\nconst DATA = ")
        json.dump(data, f, indent=1, sort_keys=True)
        f.write(";\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
