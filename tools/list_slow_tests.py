"""Regenerate test tiers from a completed, unfiltered pytest --durations run.

Run with PYTHONUTF8=1, TZ=UTC, PYTHONPATH=src and an external PYTHONPYCACHEPREFIX.
Only node IDs and aggregate counts are emitted; the source log stays local.
"""

from __future__ import annotations

import argparse
import io
import re
import runpy
import sys
from collections import defaultdict
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
DURATION = re.compile(r"^\s*(\d+(?:\.\d+)?)s\s+(?:setup|call|teardown)\s+(tests/.*::.+?)\s*$")


def read_duration_log(path: Path) -> str:
    raw = path.read_bytes()
    # Windows PowerShell 5 redirection writes UTF-16; pwsh/Python use UTF-8.
    encoding = "utf-16" if raw.startswith((b"\xff\xfe", b"\xfe\xff")) else "utf-8-sig"
    return io.StringIO(raw.decode(encoding), newline=None).read()


def parse_durations(text: str, threshold: float = 2.0) -> set[str]:
    totals = defaultdict(float)
    for line in text.splitlines():
        match = DURATION.match(line)
        if match:
            totals[match[2]] += float(match[1])
    if not totals:
        raise ValueError("no per-test durations found; use --durations=0 --durations-min=0")
    return {nodeid for nodeid, seconds in totals.items() if seconds >= threshold}


def select_slow(measured: set[str], real_kit: set[str], keep_fast: set[str]) -> set[str]:
    return (measured - keep_fast) | real_kit


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("durations", type=Path, help="local completed full-suite pytest output")
    parser.add_argument("--allow-failed-profile", action="store_true",
                        help="use failed/skipped run for timing classification only, never pass evidence")
    args = parser.parse_args()
    text = read_duration_log(args.durations)
    if not re.search(r"\b\d+ passed\b.*\bin \d+(?:\.\d+)?s\b", text):
        parser.error("profile has no completed pytest summary")
    failed = re.search(r"\b\d+ (?:failed|errors?|skipped)\b", text) is not None
    if failed and not args.allow_failed_profile:
        parser.error("profile must be a passing full run, with no failures/errors/skips")
    if failed:
        print("WARNING: failed/skipped profile used for timings only; not pass evidence", file=sys.stderr)
    if re.search(r"\b\d+ deselected\b", text):
        parser.error("profile must be unfiltered (no deselected tests)")
    try:
        measured = parse_durations(text)
    except ValueError as exc:
        parser.error(str(exc))

    policy = runpy.run_path(str(ROOT / "tests" / "conftest.py"))

    class Collection:
        def __init__(self):
            self.real_kit: set[str] = set()
            self.collected: set[str] = set()
            self.keep_fast: set[str] = set()

        @pytest.hookimpl(tryfirst=True)
        def pytest_collection_modifyitems(self, items):
            self.collected = {item.nodeid for item in items}
            self.real_kit = {item.nodeid for item in items if policy["requires_real_kit"](item)}
            self.keep_fast = {item.nodeid for item in items if policy["keep_synthetic_cli_fast"](item)}

    collection = Collection()
    # No tests/fixtures run. Hide normal node listings; errors never produce a list.
    with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
        result = pytest.main([str(ROOT / "tests"), "--rootdir", str(ROOT), "--collect-only",
                              "-q", "-o", "addopts=--import-mode=importlib", "-p", "no:cacheprovider"],
                             plugins=[collection])
    if result != pytest.ExitCode.OK:
        parser.error("collection failed; no slow list written")
    unknown = measured - collection.collected
    if unknown:
        parser.error(f"profile contains {len(unknown)} node IDs absent from this revision; reprofile")
    selected = select_slow(measured, collection.real_kit, collection.keep_fast)
    destination = ROOT / "tests" / "slow_tests.txt"
    destination.write_text(
        "# Generated by tools/list_slow_tests.py; exact pytest node IDs, sorted.\n"
        "# >=2s reported setup+call+teardown, plus all real-kit tests; synthetic gate/verify CLI retained.\n"
        + "".join(nodeid + "\n" for nodeid in sorted(selected)), encoding="utf-8", newline="\n",
    )
    print(f"Wrote {len(selected)} slow tests ({len(collection.real_kit)} real-kit) to tests/slow_tests.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
